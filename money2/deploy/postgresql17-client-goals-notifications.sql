BEGIN;
ALTER TABLE money2_metas_financeiras
    ADD COLUMN IF NOT EXISTS clientes_ativos_final BIGINT,
    ADD COLUMN IF NOT EXISTS clientes_em_dia_final BIGINT,
    ADD COLUMN IF NOT EXISTS clientes_atraso_final BIGINT,
    ADD COLUMN IF NOT EXISTS clientes_novos_final BIGINT;
ALTER TABLE money2_metas_financeiras DROP CONSTRAINT IF EXISTS ck_money2_meta_tipo;
ALTER TABLE money2_metas_financeiras ADD CONSTRAINT ck_money2_meta_tipo CHECK
    (tipo IN ('EMPRESTADO','RECEBIDO','LUCRO','CLIENTES_ATIVOS','CLIENTES_EM_DIA','CLIENTES_ATRASO'));
ALTER TABLE money2_metas_financeiras DROP CONSTRAINT IF EXISTS ck_money2_meta_valor;
ALTER TABLE money2_metas_financeiras ADD CONSTRAINT ck_money2_meta_valor CHECK
    ((valor_meta > 0 OR (tipo='CLIENTES_ATRASO' AND valor_meta=0))
    AND (tipo NOT IN ('CLIENTES_EM_DIA','CLIENTES_ATRASO') OR valor_meta<=100)
    AND (tipo<>'CLIENTES_ATIVOS' OR valor_meta=TRUNC(valor_meta)));

CREATE TABLE IF NOT EXISTS money2_notification_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    payments BOOLEAN NOT NULL DEFAULT false,
    goals BOOLEAN NOT NULL DEFAULT false,
    payments_since TIMESTAMPTZ NOT NULL DEFAULT now(),
    goals_since TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS money2_notification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key TEXT NOT NULL UNIQUE,
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('PAYMENT','GOAL')),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    region_ids BIGINT[] NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_money2_notification_created ON money2_notification_events(created_at DESC);
-- Do not replay old PIX payments after enabling the feature.
CREATE TABLE IF NOT EXISTS money2_notification_state (id INTEGER PRIMARY KEY, started_at TIMESTAMPTZ NOT NULL);
INSERT INTO money2_notification_state VALUES (1,now()) ON CONFLICT DO NOTHING;
-- Run as the database maintenance role, without granting CREATE to the app.
GRANT SELECT,INSERT,UPDATE,DELETE ON money2_notification_preferences,money2_notification_events TO money2_app;
GRANT SELECT ON money2_notification_state TO money2_app;
GRANT USAGE,SELECT ON SEQUENCE money2_notification_events_id_seq TO money2_app;
COMMIT;
