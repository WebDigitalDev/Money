BEGIN;

CREATE TABLE IF NOT EXISTS money2_metas_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id BIGINT NOT NULL REFERENCES regioes(id),
    tipo VARCHAR(20) NOT NULL,
    valor_meta NUMERIC(19,2) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    criado_por BIGINT NOT NULL,
    dtcad TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dtalter TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_money2_meta_tipo
        CHECK (tipo IN ('EMPRESTADO', 'RECEBIDO', 'LUCRO')),
    CONSTRAINT ck_money2_meta_valor CHECK (valor_meta > 0),
    CONSTRAINT ck_money2_meta_periodo CHECK (data_fim >= data_inicio)
);

CREATE INDEX IF NOT EXISTS idx_money2_metas_regiao_periodo
    ON money2_metas_financeiras (regiao_id, data_inicio, data_fim);

ALTER TABLE money2_metas_financeiras
    ADD COLUMN IF NOT EXISTS valor_alcancado_final NUMERIC(19,2),
    ADD COLUMN IF NOT EXISTS finalizada_em TIMESTAMP WITHOUT TIME ZONE;

COMMIT;
